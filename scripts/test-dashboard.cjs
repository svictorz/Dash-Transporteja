const now = new Date(2026, 10, 7, 12)
const routes = [route(1), route(2, { created_by_user_id: 'other', freight_value: 999999 }), route(3, { pickup_date: '2026-10-07', freight_value: 2000 }), route(4, { pickup_date: '2026-11-01', financial_calculation_version: 1, driver_value: 400, net_freight_value: 444, commission_value: 123 }), route(5, { pickup_date: '', estimated_delivery: '2026-11-03', freight_value: 500 }), route(6, { pickup_date: '', estimated_delivery: '', freight_value: 42 })]
const metrics = buildDashboardMetrics(routes, 'seller', 'month', now, 20)
