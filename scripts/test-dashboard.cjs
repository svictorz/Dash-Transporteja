const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const root = path.resolve(__dirname, '..')
const modules = new Map()
function load(file) {
  const filename = path.resolve(root, file)
  if (modules.has(filename)) return modules.get(filename)
  const context = { exports: {}, Date, Map, require: name => load(name.startsWith('@/') ? `${name.slice(2)}.ts` : path.relative(root, path.resolve(path.dirname(filename), `${name}.ts`))) }
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, context, { filename })
  modules.set(filename, context.exports)
  return context.exports
}
