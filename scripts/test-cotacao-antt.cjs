const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const filename = path.resolve(__dirname, '../lib/utils/cotacao-antt.ts')
const context = { exports: {}, require: () => ({}) }
vm.runInNewContext(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context)
const { anttReferenceRows, anttMinimumForVehicle, ANTT_REFERENCE_FLEET } = context.exports
const rows = anttReferenceRows([{ name: 'Truck', axles: 3, payloadKg: 14000, anttCcd: 5.2177, anttFixed: 541.86 }], 1207, 3585)
assert.equal(rows.length, 1)
assert.equal(rows[0].reference, 6839.62)
assert.equal(rows[0].fit, 'compatível')
const officialRows = anttReferenceRows([], 1207, 3585, 2.81)
assert.equal(officialRows.length, 10)
assert.equal(officialRows[0].fit, 'incompatível')
assert.equal(officialRows[1].fit, 'incompatível')
assert.equal(officialRows[2].fit, 'compatível')
assert.equal(officialRows[0].reference, 5368.92)
assert.equal(ANTT_REFERENCE_FLEET.length, 10)
assert.equal(anttReferenceRows([{ name: 'Truck', axles: 3, anttCcd: 5.2177, anttFixed: 541.86 }], 0).length, 0)
assert.equal(anttMinimumForVehicle(ANTT_REFERENCE_FLEET, '3/4', 1284.8), 5685.86)
assert.equal(anttMinimumForVehicle(ANTT_REFERENCE_FLEET, 'Inexistente', 1284.8), null)
console.log('PASS: referência ANTT apenas com coeficientes configurados')
